const assert = require("node:assert/strict")
const fs = require("node:fs/promises")
const os = require("node:os")
const path = require("node:path")
const { nodeSqliteTest, execSqlite, querySqlite } = require("./helpers/sqlite")
const test = require("node:test")
const { RepositorySession, operationMaterializesWorktree } = require("..")

test("normalized schema preserves both sides' records, recomputes conflicts, reopens and undoes", nodeSqliteTest, async () => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), "graft-schema-phase-"))
  const source = path.join(root, "source"), local = path.join(root, "local"), remote = path.join(root, "remote")
  let incoming, ours
  const edit = execSqlite
  const read = () => querySqlite(path.join(local,"projects.db"), "SELECT * FROM Projects ORDER BY id")
  try {
    await Promise.all([source,local,remote].map(folder => fs.mkdir(folder)))
    edit(path.join(source,"projects.db"), "CREATE TABLE Projects (id INTEGER PRIMARY KEY, Owner TEXT); INSERT INTO Projects VALUES (1,'Alex'),(2,'Sam')")
    incoming = await RepositorySession.open(source)
    await incoming.init(); await incoming.addAll(); await incoming.commit("base")
    await incoming.configureRemote({name:"origin",url:`fs://${remote}`,upstreamBranch:"main"})
    await incoming.push()
    ours = await RepositorySession.open(local)
    await ours.cloneRepository({remoteUrl:`fs://${remote}`})
    edit(path.join(source,"projects.db"), "ALTER TABLE Projects RENAME COLUMN Owner TO Assignee; UPDATE Projects SET Assignee='Avery' WHERE id=1; INSERT INTO Projects VALUES (4,'Incoming only')")
    await incoming.addAll(); await incoming.commit("incoming rename and records"); await incoming.push()
    edit(path.join(local,"projects.db"), 'ALTER TABLE Projects RENAME COLUMN Owner TO "Project lead"; UPDATE Projects SET "Project lead"=\'Blair\' WHERE id=1; INSERT INTO Projects VALUES (3,\'Local only\')')
    await ours.addAll()
    const head = await ours.commit("local rename and records")
    await ours.fetch()
    const plan = await ours.planMerge({revision:"origin/main",expectedHead:head.commit.id})
    const applied = await ours.applyMerge({revision:"origin/main",expectedHead:head.commit.id,planToken:plan.plan_token})
    const originalToken = applied.merge.state_token
    const inputs = {}
    for (const [version, column] of [["base","Owner"],["ours","Project lead"],["theirs","Assignee"]]) {
      const output = path.join(root,`${version}.db`)
      await ours.exportMergeSqliteVersion({path:"projects.db",version,output,expectedStateToken:originalToken})
      await fs.chmod(output,0o600)
      if (column !== "Project lead") edit(output, `ALTER TABLE Projects RENAME COLUMN "${column}" TO "Project lead"`)
      inputs[version] = output
    }
    const normalized = await ours.normalizeMergeSqliteInputs({path:"projects.db",...inputs,expectedStateToken:originalToken})
    assert.equal(normalized.merge.unmerged_count,1)
    assert.notEqual(normalized.merge.state_token,originalToken)
    assert.deepEqual(read().map(row => row.id),[1,2,3,4])
    assert.equal(read()[0]["Project lead"],"Blair")
    await assert.rejects(ours.normalizeMergeSqliteInputs({path:"projects.db",...inputs,expectedStateToken:originalToken}), {code:"GRAFT_SDK_REPOSITORY_STALE"})
    await ours.close(); ours = await RepositorySession.open(local)
    const status = await ours.getMergeStatus()
    const conflicts = await ours.listMergeConflicts({path:"projects.db",expectedStateToken:status.state_token})
    assert(conflicts.items.some(item => item.reason === "schema_normalized" && item.status === "resolved"))
    const row = conflicts.items.find(item => item.kind === "row" && item.status === "unresolved")
    assert(row)
    assert(row.columns.includes("Project lead"))
    const resolved = await ours.resolveMergeRow({path:"projects.db",table:"Projects",identity:row.key ?? row.rowid,result:"theirs",expectedStateToken:status.state_token})
    assert.equal(resolved.merge.unmerged_count,0)
    assert.deepEqual(read().map(row => [row.id,row["Project lead"]]),[[1,"Avery"],[2,"Sam"],[3,"Local only"],[4,"Incoming only"]])
    const undone = await ours.unresolveMergePath({path:"projects.db",expectedStateToken:resolved.merge.state_token})
    assert.equal(undone.merge.unmerged_count,1)
    assert.deepEqual(read().map(row => [row.id,row["Project lead"]]),[[1,"Blair"],[2,"Sam"],[3,"Local only"]])
    const restored = await ours.listMergeConflicts({path:"projects.db",expectedStateToken:undone.merge.state_token})
    assert(restored.items.some(item => item.kind === "schema" && item.status === "unresolved"))
    assert(!restored.items.some(item => item.reason === "schema_normalized"))
    assert.equal(operationMaterializesWorktree("normalizeMergeSqliteInputs"),true)
    await ours.abortMerge({expectedStateToken:undone.merge.state_token})
  } finally {
    await incoming?.close(); await ours?.close()
    await fs.rm(root,{recursive:true,force:true})
  }
})
