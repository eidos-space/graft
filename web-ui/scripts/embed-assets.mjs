import { readdir, writeFile } from "node:fs/promises";
import { dirname, extname, join, sep } from "node:path";
import { fileURLToPath } from "node:url";

const directory = join(dirname(fileURLToPath(import.meta.url)), "../generated");
const mimeTypes = {
  ".html": "text/html; charset=utf-8",
  ".js": "text/javascript; charset=utf-8",
  ".mjs": "text/javascript; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".wasm": "application/wasm",
};
const files = (await readdir(directory, { recursive: true }))
  .map((file) => file.split(sep).join("/"))
  .filter((file) => extname(file) in mimeTypes)
  .sort();
const entries = files.map((file) => {
  const path = file === "index.html" ? "/" : `/${file}`;
  return `    EmbeddedAsset { path: ${JSON.stringify(path)}, content_type: ${JSON.stringify(mimeTypes[extname(file)])}, bytes: include_bytes!(${JSON.stringify(file)}) },`;
});
await writeFile(
  join(directory, "assets.rs"),
  `// Generated by web-ui/scripts/embed-assets.mjs. Do not edit.\nconst ASSETS: &[EmbeddedAsset] = &[\n${entries.join("\n")}\n];\n`,
);
